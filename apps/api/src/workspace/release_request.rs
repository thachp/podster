/// The longest task ID a request may name: as long as a principal's ID may be.
const MAX_TASK_ID: usize = 128;
/// How many labels are made ready for one request. A label is thrown away only if it holds Podster's name or a word of
/// the room's, which a random one almost never does.
const LABEL_TRIES: usize = 4;
/// The shortest word of the room's name or handle a label must not hold. A shorter one would turn away most labels.
const AVOIDED_WORD: usize = 4;

/// What was read outside the room before the transaction. Never taken from a request.
pub(super) struct RequestReads {
    room: OnReads,
    /// The requester's own standing: whether they still belong to the organization their place here is held in.
    requester: Asked,
    /// Whoever gave the requester their `deploy` grant, as the rows named them when asked: whether they still hold.
    giver: Asked,
    /// Randomness for a label, made outside the transaction, used only if the room has none current.
    labels: Vec<[u8; 16]>,
}

/// Whether someone may ask at all, by the room's rows alone: asked before anything outside the room is read, and again
/// before a stored answer is given back.
pub(super) fn may_ask(who: &Participant) -> R<()> {
    may_ask_for_release(&who.caller).map_err(denied)
}

/// A policy refusal, as the API answers it. Who is asking and a grant are 403; a fact of the room's is 409.
fn denied(denial: ReleaseDenial) -> ApiError {
    match denial {
        ReleaseDenial::Grant(refusal) => {
            // error-codes: grant_required, grant_expired, grant_stale
            ApiError::api(403, refusal.code())
        }
        // `public_participant` is who is asking.
        ReleaseDenial::PublicParticipant => {
            let code = denial.code();
            // error-codes: public_participant
            ApiError::api(403, code)
        }
        other => super::release_config::denial(other),
    }
}

/// A refusal of core's, as the API answers it.
fn refused(refusal: RequestRefusal) -> ApiError {
    let status = match refusal {
        RequestRefusal::Commit(podster_core::release::CommitRefusal::UnknownEnvironment) => 400,
        RequestRefusal::Limit(_) => 429,
        _ => 409,
    };
    // `RequestRefusal::code` is marked reasons, since its codes are data elsewhere; these are what a request answers.
    let code = refusal.code();
    // error-codes: commit_not_releasable, invalid_argument, reviewer_rule_changed, no_releaser, release_pending, release_limit
    ApiError::api(status, code)
}

/// What the request names: `{ task_id, commit_sha }`, and `environment` only if it is the one there is. Nothing else.
struct Named {
    task_id: String,
    commit_sha: String,
    environment: String,
}

fn parse(body: &Value) -> R<Named> {
    let fields = body.as_object().ok_or_else(ApiError::invalid_argument)?;
    if fields
        .keys()
        .any(|key| !matches!(key.as_str(), "task_id" | "commit_sha" | "environment"))
    {
        return Err(ApiError::invalid_argument());
    }
    let task_id = body["task_id"]
        .as_str()
        .filter(|id| !id.is_empty() && id.len() <= MAX_TASK_ID)
        .ok_or_else(ApiError::invalid_argument)?;
    let commit_sha = body["commit_sha"]
        .as_str()
        .ok_or_else(ApiError::invalid_argument)?;
    let environment = match body.get("environment") {
        None => podster_core::release::ENVIRONMENT,
        Some(value) => value.as_str().ok_or_else(ApiError::invalid_argument)?,
    };
    Ok(Named {
        task_id: task_id.to_owned(),
        commit_sha: commit_sha.to_owned(),
        environment: environment.to_owned(),
    })
}

/// A release as the contract's `Release` gives it. `result_url` is never set by a request. `rollback_to` names the
/// earlier release a rollback rolls back to, and is null for any other release.
pub(super) fn view(release: &Value) -> Value {
    json!({
        "id": release["id"],
        "commit_sha": release["commit_sha"],
        "environment": release["environment"],
        "state": release["state"],
        "requested_by": release["requested_by"],
        "requested_at": release["requested_at"],
        "approved_by": release["approved_by"],
        "approved_at": release["approved_at"],
        "declined_by": release["declined_by"],
        "declined_at": release["declined_at"],
        "result_url": Value::Null,
        "failure_code": release["failure_code"],
        "finished_at": release["finished_at"],
        "rollback_to": release["rollback_to"],
    })
}

/// The task's merge record, as the job's recheck reads it (`release_recheck::gather`): the commit, its repository,
/// whether Podster's merge job called and confirmed it, and whether the task is completed. And whether the task's
/// review meets the room's reviewer rule now.
type Merged = (String, i64, bool, bool, bool);

fn commit_of(sql: &SqlStorage, task_id: &str) -> R<(Option<Merged>, bool)> {
    let change = rows(
        sql,
        "SELECT c.merge_sha, c.provider_repo_id, c.merge_state, c.merge_called_at, c.merge_finished_at, c.reviewer_id, t.status
           FROM task_change c JOIN task t ON t.id = c.task_id WHERE c.task_id = ?",
        vec![task_id.into()],
    )?;
    let change = change.first();
    let commit = change.and_then(|row| {
        let succeeded = row["merge_state"].as_str() == Some("succeeded");
        Some((
            text(&row["merge_sha"])?,
            int(&row["provider_repo_id"]),
            succeeded && !row["merge_called_at"].is_null(),
            succeeded && !row["merge_finished_at"].is_null(),
            row["status"].as_str() == Some("completed"),
        ))
    });
    let reviewer_rule_holds = !store::requires_person_review(sql)?
        || change
            .and_then(|row| row["reviewer_id"].as_str())
            .is_some_and(|reviewer| parse_kind_of(reviewer) == PrincipalKind::Person);
    Ok((commit, reviewer_rule_holds))
}

/// The room's current label, or a new one made from the randomness read before the transaction. A new label is the
/// room's only current one: an unpublish retired any earlier one, and the table admits one current label.
fn current_label(sql: &SqlStorage, candidates: &[[u8; 16]], now: i64) -> R<String> {
    if let Some(label) = rows(sql, "SELECT label FROM app_label WHERE current = 1", vec![])?
        .first()
        .and_then(|row| text(&row["label"]))
    {
        return Ok(label);
    }
    let room = rows(sql, "SELECT name, public_handle FROM workspace", vec![])?;
    let room = room.first();
    let words: Vec<String> = ["name", "public_handle"]
        .into_iter()
        .filter_map(|column| room.and_then(|row| text(&row[column])))
        .flat_map(|value| {
            value
                .split(|c: char| !c.is_ascii_alphanumeric())
                .filter(|word| word.len() >= AVOIDED_WORD)
                .map(str::to_ascii_lowercase)
                .collect::<Vec<_>>()
        })
        .collect();
    let avoid: Vec<&str> = words.iter().map(String::as_str).collect();
    let used = |label: &str| -> R<bool> {
        Ok(!rows(
            sql,
            "SELECT 1 AS used FROM app_label WHERE label = ?",
            vec![label.into()],
        )?
        .is_empty())
    };
    for random in candidates {
        let label = label_from_random(*random);
        if label_acceptable(&label, &avoid) && !used(&label)? {
            exec(
                sql,
                "INSERT INTO app_label (label, current, created_at) VALUES (?, 1, ?)",
                vec![label.as_str().into(), now.into()],
            )?;
            return Ok(label);
        }
    }
    Err(ApiError::internal("no acceptable label"))
}

/// Whether the caller may ask for a release now, on the room's rows and what was read outside, in the room's
/// transaction: `may_ask`, then `authorize_release_request`. **An outside fact that couldn't be read is taken as
/// holding and remembered,** so a fact that was read and fails refuses with its own code whatever else couldn't be
/// read; only when nothing read fails does an unread one answer `standing_unknown`. Nothing here names a task, so who
/// is asking is settled before anything is said about one.
///
/// Run by the command before anything else, and again before a stored answer is replayed (`command_checked`), so a
/// retry under the same key from someone who has since lost their grant, its giver's authority, or a room where
/// release may happen, is refused with the code that holds now and writes nothing.
pub(super) fn standing(sql: &SqlStorage, who: &Participant, reads: &RequestReads) -> R<()> {
    let now = release_now(sql);
    let caller = &who.caller;
    may_ask(who)?;
    let (room, room_unknown) = room_assuming(sql, &reads.room)?;
    let requester_holds = settled(sql, &reads.requester, Some(&caller.id), false)?;
    let grant = deploy_grant(sql, &caller.id, now)?;
    let giver = grant.as_ref().map(|grant| grant.delegated_by.clone());
    let giver_holds = settled(sql, &reads.giver, giver.as_deref(), true)?;
    let holder = match &giver {
        Some(giver) => repositories::recorded_giver(sql, giver)?
            .and_then(|g| delegation_holder(giver, g.kind, g.role, giver_holds.unwrap_or(true))),
        None => None,
    };
    let grant = grant.as_ref().map(|g| DeployGrant {
        principal: &caller.id,
        action: DEPLOY_ACTION,
        provider_repo_id: g.provider_repo_id,
        delegated_by: &g.delegated_by,
        expires_at: g.expires_at,
        revoked_at: None,
    });
    let link_repo_id = rows(sql, "SELECT provider_repo_id FROM repo_link", vec![])?
        .first()
        .map_or(0, |link| int(&link["provider_repo_id"]));
    let standing = ReleaseStanding {
        grant: grant.as_ref(),
        link_repo_id,
        delegation_holder: holder,
        through_public_claim: public_claims::is_public_participant(sql, &caller.id)?,
        // Never read: a person's request.
        agent_connected: false,
        now,
    };
    authorize_release_request(caller, &room, &standing, requester_holds.unwrap_or(true))
        .map_err(denied)?;
    // Only now, with nothing read failing, does a fact that couldn't be read decide: nothing is written on it.
    if room_unknown || requester_holds.is_none() || giver_holds.is_none() {
        return Err(standing_unknown());
    }
    Ok(())
}

/// `POST releases`, in the room's transaction, after [`Workspace::release_request_reads`]. **Run only as the handler of
/// `command_checked` whose recheck is [`standing`]:** that recheck runs first on every attempt, a first one and a replay
/// alike, so who is asking, and where, is settled before the task they named is looked at. It isn't asked again here:
/// the second call survived its own mutation, which is how it was found to change nothing (review standards, rule 2).
pub(super) fn handle(
    sql: &SqlStorage,
    who: &Participant,
    body: &Value,
    reads: &RequestReads,
) -> R<Value> {
    let now = release_now(sql);
    // Release bookkeeping first, as at the start of every release command: a release left from before an unpublish is
    // ended, so it neither holds its commit pending nor is offered for approval.
    release_commit::end_stale(sql, now)?;
    let named = parse(body)?;
    // The task, as the caller may see it: one they can't see is one that isn't there.
    let task = load_task(sql, &named.task_id)?
        .filter(|task| can_see_task(&who.caller, task))
        .ok_or_else(ApiError::task_not_found)?;
    let asked = AskedFor {
        task_id: Some(&task.id),
        commit_sha: &named.commit_sha,
        environment: &named.environment,
        rollback_to: None,
    };
    record(sql, who, &asked, reads, now)
}

/// What a request asks for, as the room records it: a task's commit in an environment, and, for a rollback
/// (`release_rollback`), the earlier release it rolls back to.
pub(super) struct AskedFor<'a> {
    /// The task whose merged commit is asked for; `None` for a rollback to a release that names none, whose commit
    /// can't then be releasable.
    pub(super) task_id: Option<&'a str>,
    pub(super) commit_sha: &'a str,
    pub(super) environment: &'a str,
    pub(super) rollback_to: Option<&'a str>,
}

/// Core's decision on what is asked, then the release recorded `awaiting_approval`, in the caller's transaction, with
/// its audit record and its event. Shared by a request and a rollback, so both are counted and refused alike: a
/// rollback is one of the room's 20 asks a rolling day, as any request is.
pub(super) fn record(
    sql: &SqlStorage,
    who: &Participant,
    asked: &AskedFor,
    reads: &RequestReads,
    now: i64,
) -> R<Value> {
    let caller = &who.caller;
    let link_repo_id = rows(sql, "SELECT provider_repo_id FROM repo_link", vec![])?
        .first()
        .map_or(0, |link| int(&link["provider_repo_id"]));

    // What, on the room's own rows.
    let (commit, reviewer_rule_holds) = match asked.task_id {
        Some(task) => commit_of(sql, task)?,
        None => (None, true),
    };
    let record = commit.as_ref().map(|c| CommitRecord {
        sha: &c.0,
        provider_repo_id: c.1,
        merged_by_podster: c.2,
        confirmed_on_default_branch: c.3,
        task_completed: c.4,
    });
    let pending = rows(
        sql,
        "SELECT state FROM release WHERE commit_sha = ?",
        vec![asked.commit_sha.into()],
    )?
    .iter()
    .filter_map(|row| row["state"].as_str())
    .filter_map(|name| ReleaseState::ALL.into_iter().find(|s| s.name() == name))
    .any(pending_for_commit);
    let asked_at: Vec<i64> = rows(
        sql,
        "SELECT requested_at FROM release WHERE requested_at >= ?",
        vec![
            podster_core::release::window_start(now, podster_core::release::RELEASE_WINDOW_MS)
                .into(),
        ],
    )?
    .iter()
    .map(|row| int(&row["requested_at"]))
    .collect();
    request_release(&ReleaseRequest {
        asked_sha: asked.commit_sha,
        environment: asked.environment,
        commit: record.as_ref(),
        room_repo_id: link_repo_id,
        reviewer_rule_holds,
        app_held: releasers::held_until(sql)?.is_some(),
        pending_for_commit: pending,
        asked_at: &asked_at,
        now,
    })
    .map_err(refused)?;

    // Recorded, awaiting a person's approval, under the configuration and the epoch the room has now.
    let config = rows(
        sql,
        "SELECT version, release_epoch FROM release_config",
        vec![],
    )?;
    let config = config
        .first()
        .ok_or_else(|| ApiError::internal("release is on with no configuration"))?;
    let label = current_label(sql, &reads.labels, now)?;
    let id = format!("rel_{}", uuid::Uuid::new_v4().simple());
    exec(
        sql,
        "INSERT INTO release (id, commit_sha, task_id, state, label, config_version, release_epoch, requested_by, requested_at, updated_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        vec![
            id.as_str().into(),
            asked.commit_sha.into(),
            asked.task_id.map_or(V::Null, V::from),
            REQUESTED_STATE.name().into(),
            label.as_str().into(),
            int(&config["version"]).into(),
            int(&config["release_epoch"]).into(),
            caller.id.as_str().into(),
            now.into(),
            now.into(),
        ],
    )?;
    let mut trail = json!({ "state": REQUESTED_STATE.name(), "task_id": asked.task_id, "commit_sha": asked.commit_sha });
    if let Some(target) = asked.rollback_to {
        exec(
            sql,
            "INSERT INTO release_rollback (release_id, rollback_to) VALUES (?, ?)",
            vec![id.as_str().into(), target.into()],
        )?;
        trail["rollback_to"] = target.into();
    }
    audit(
        sql,
        caller,
        "release.requested",
        &id,
        None,
        Some(trail.to_string()),
        now,
    )?;
    // About the release, by its ID, to those who may approve it.
    store::record_event_about(
        sql,
        "release.requested",
        &caller.id,
        Some(&id),
        None,
        &Transition::NONE,
        roles::room_approvers(sql, &caller.id)?,
        now,
    )?;
    Ok(view(&full_row(sql, &id)?))
}

/// A release's whole row, as [`view`] answers it.
pub(super) fn full_row(sql: &SqlStorage, id: &str) -> R<Value> {
    rows(
        sql,
        &format!("SELECT {RELEASE_COLUMNS}, environment, requested_by, requested_at, approved_by, approved_at, declined_by, declined_at, finished_at,
               (SELECT rollback_to FROM release_rollback WHERE release_id = release.id) AS rollback_to FROM release WHERE id = ?"),
        vec![id.into()],
    )?
    .into_iter()
    .next()
    .ok_or_else(|| ApiError::internal("a release just written isn't there"))
}

impl Workspace {
    /// Everything `POST releases` reads outside the room, before its transaction. The release path's gate first, as
    /// every release command passes it.
    pub(super) async fn release_request_reads(&self, caller_id: &str) -> R<RequestReads> {
        self.release_path_open().await?;
        let room = self.on_reads().await?;
        let requester = self.still_holds(Some(caller_id), false).await?;
        let sql = self.state.storage().sql();
        let giver =
            deploy_grant(&sql, caller_id, release_now(&sql))?.map(|grant| grant.delegated_by);
        let giver = self.still_holds(giver.as_deref(), true).await?;
        let mut labels = Vec::with_capacity(LABEL_TRIES);
        while labels.len() < LABEL_TRIES {
            let random = super::hostname::random_32()?;
            let (first, second) = random.split_at(16);
            for half in [first, second] {
                let mut bytes = [0u8; 16];
                bytes.copy_from_slice(half);
                labels.push(bytes);
            }
        }
        Ok(RequestReads {
            room,
            requester,
            giver,
            labels,
        })
    }
}
