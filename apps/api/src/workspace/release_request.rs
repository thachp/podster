//! Asking for a release of a task's merged commit (`requestRelease`, `POST /v1/workspaces/{ws}/releases`; M6 step 6,
//! ADR 0010's "Authority, approval and triggers"). This is the first half of "a `deploy_release` command, then a
//! person's approval": it records a release `awaiting_approval` and nothing else. **Nothing is read from a repository,
//! uploaded or served by it,** and the release job never takes up a release a person hasn't approved
//! (`release_recheck::job_owns`). Approving and declining are `release_approval`'s.
//!
//! **Who** is `podster_policy::release::authorize_release_request`: a person in the room, not there through a public
//! claim, holding a live `deploy` grant on the room's repository from someone who still holds release authority, and
//! still in the organization their place here is held in; and only where release may happen at all, a public room
//! first. **An agent never asks here yet:** the Worker refuses one by its kind, and so does the room. The rows a request
//! writes keep who asked and not the person who controls them, so an agent's release couldn't be rechecked; its request
//! arrives with the `deploy_release` capability, which records that person.
//!
//! **What** is `podster_core::release_request::request_release`: exactly the commit Podster's own merge confirmed for
//! the task named, on the room's own repository, the room's reviewer rule as it is now, no hold because nobody may
//! release, no release of the same commit already waiting or on its way, and the room's 20 asks a rolling day.
//!
//! **What is read outside the room, and when,** before the transaction, as every release command reads it: first the
//! release path's gate, which refuses the whole command as a route that isn't built while `RELEASE_PATH_COMPLETE` is
//! false in a deployment with release on and a provider configured; then the deployment's setting, the organization's
//! provisioning delegation and release switch (each applied as read); then the requester's own `Principal` and the
//! grant giver's. Inside the transaction an answer about anyone or anything the rows no longer name says nothing. **A
//! fact that was read and fails refuses; one that couldn't be read, with nothing read failing, is `standing_unknown`
//! (503), which writes nothing.** The content domain's stop isn't read: a request publishes nothing, and the approval
//! and every pass of the job read it.
//!
//! **The order of refusals, in the transaction:** who is asking and where, wholly ([`standing`]: in the room and a
//! person; then the room's facts in `release_room_allows`'s order; then the grant, a public claim, and the requester's
//! own record), before the body's task is looked at; then, if nothing read failed, `standing_unknown` for a fact that
//! couldn't be read; then the body, the task as the caller may see it (`task_not_found`), and core's order. [`standing`]
//! is also what a replay of a stored answer is checked against, so a retry under the same key from someone who has
//! since lost their grant, or from a room where release no longer may happen, is refused by the code that holds now.
//!
//! **What a request writes,** in one transaction with its idempotency record: the release, `awaiting_approval`, under
//! the room's current configuration version and release epoch and its current label; the label itself if the room has
//! none current, which is the first request ever or the first since an unpublish retired the last one (generated by the
//! server, random, and never used again: `podster_core::release::label_from_random`); the audit record
//! `release.requested` by the requester; and the event `release.requested`, about the release by its ID, to the room's
//! owner and its admins who are people (`roles::room_approvers`): those who may approve it. An agent holding the admin
//! role hears nothing of it. **The label isn't written to D1's lookup table here,** and the room's
//! default host has no serve row yet: neither is needed until a release can be queued, which approval writes
//! (`release_approval`), and the room's alarm indexes every label not yet in the table, this one included.
//!
//! The route exists only while the deployment's setting is on, as every M6 route; otherwise the room answers it as an
//! unknown route. Logs carry IDs and codes only.
